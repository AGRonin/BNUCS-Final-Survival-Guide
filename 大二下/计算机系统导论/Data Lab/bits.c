/* 
 * floatAbsVal - Return bit-level equivalent of absolute value of f for
 *   floating point argument f.
 *   Both the argument and result are passed as unsigned int's, but
 *   they are to be interpreted as the bit-level representations of
 *   single-precision floating point values.
 *   When argument is NaN, return argument..
 *   Legal ops: Any integer/unsigned operations incl. ||, &&. also if, while
 *   Max ops: 10
 *   Rating: 2
 */
unsigned floatAbsVal(unsigned uf){
	unsigned exp=(uf>>23)&0xFF;
	unsigned frac=uf&0x7FFFFF;
	if(exp==0xFF && frac!=0)
	{
		return uf;
	}
  	return uf&0x7FFFFFFF;
}
/* 
 * floatScale1d2 - Return bit-level equivalent of expression 0.5*f for
 *   floating point argument f.
 *   Both the argument and result are passed as unsigned int's, but
 *   they are to be interpreted as the bit-level representation of
 *   single-precision floating point values.
 *   When argument is NaN, return argument
 *   Legal ops: Any integer/unsigned operations incl. ||, &&. also if, while
 *   Max ops: 30
 *   Rating: 4
 */
unsigned floatScale1d2(unsigned uf) {
	unsigned sign=uf&(0x01<<31);
	unsigned exp=(uf>>23)&0xFF;
	unsigned frac=uf&0x7FFFFF;
	unsigned roundbit=frac&0x01;
	unsigned roundup=(frac>>1)&0x01;
	if(exp==0xFF)
	{
		return uf;
	}
	if(exp==0x00)
	{
		if(roundbit && roundup)
		{
			frac+=1;
		}
		frac=frac>>1;
		return sign|exp|frac;
	}
	if(exp==0x01)
	{
		frac=frac|(0x1<<23);
		if(roundbit && roundup)
		{
			frac+=1;
		}
		frac=frac>>1;
		exp=0x00;
		return sign|exp|frac;
	}
	exp=exp-1;
	exp=exp<<23;
	return sign|exp|frac;
}
/* 
 * floatFloat2Int - Return bit-level equivalent of expression (int) f
 *   for floating point argument f.
 *   Argument is passed as unsigned int, but
 *   it is to be interpreted as the bit-level representation of a
 *   single-precision floating point value.
 *   Anything out of range (including NaN and infinity) should return
 *   0x80000000u.
 *   Legal ops: Any integer/unsigned operations incl. ||, &&. also if, while
 *   Max ops: 30
 *   Rating: 4
 */
int floatFloat2Int(unsigned uf) {
	unsigned sign=uf&(0x01<<31);
	unsigned exp=(uf>>23)&0xFF;
	unsigned frac=uf&0x7FFFFF;
	int E=exp-127;
	int newfrac=frac|(0x1<<23);
	if(exp==0xFF || E>=31)
	{
		return 0x80000000u;
	}
	if(E<0)
	{
		return 0;
	}
	if(E>23)
	{
		newfrac=newfrac<<(E-23);
	}
	else
	{
		newfrac=newfrac>>(23-E);
	}
	if(sign)
	{
		newfrac=-newfrac;
	}
	return newfrac;
}
