/*
 * intLog2 - return floor(log base 2 of x), where x > 0
 *   Example: intLog2(16) = 4
 *   Legal ops: ! ~ & ^ | + << >>
 *   Max ops: 90
 *   Rating: 4
 */
int intLog2(int x) {
	int a16,a8,a4,a2,a1;
	a16=!!(x>>16)<<4;
	x=x>>a16;
	a8=!!(x>>8)<<3;
	x=x>>a8;
	a4=!!(x>>4)<<2;
	x=x>>a4;
	a2=!!(x>>2)<<1;
	x=x>>a2;
	a1=!!(x>>1);
	return a16+a8+a4+a2+a1;
}
